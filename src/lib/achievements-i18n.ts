const DICTS: Record<Locale, Dict> = { pt, en, it, es, fr };

export function tAch(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[locale]?.[key] ?? DICTS.pt[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      // Values may themselves be i18n keys (e.g. skill names).
      const resolved =
        typeof v === "string" && v.startsWith("ach.")
          ? (DICTS[locale]?.[v] ?? DICTS.pt[v] ?? v)
          : String(v);
      s = s.replaceAll(`{${k}}`, resolved);
    }
  }
  return s;
}
